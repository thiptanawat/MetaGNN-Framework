#!/usr/bin/env python3
"""
Aggregate the per-seed metrics produced by 06_multiseed_experiment.py.

Reads ``per_seed_metrics.json`` (a list of per-run dictionaries) and emits
three outputs under the same directory:

* ``summary_stats.csv`` -- mean, standard deviation, min, max, and the
  95% percentile bootstrap confidence interval for every reported metric.
* ``summary_stats.tex`` -- a \begin{tabular} LaTeX block ready to drop into
  the manuscript (Results section, "Multi-seed robustness" subsection).
* ``multiseed_boxplot.png`` -- per-metric boxplot figure showing the
  distribution across seeds with the point estimate marked.

Usage
-----
    python code/07_aggregate_multiseed_results.py \
        --results_dir ./results/multiseed_220 \
        --metrics auroc auprc f1 \
        --n_bootstrap 10000
"""

import argparse
import json
import logging
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
)


def bootstrap_ci(values: Sequence[float], n_bootstrap: int,
                 alpha: float = 0.05, seed: int = 2024) -> Tuple[float, float]:
    """Percentile bootstrap CI of the mean."""
    rng = np.random.default_rng(seed)
    arr = np.asarray(values, dtype=float)
    if arr.size == 0:
        return (float("nan"), float("nan"))
    means = rng.choice(arr, size=(n_bootstrap, arr.size), replace=True).mean(axis=1)
    lo, hi = np.quantile(means, [alpha / 2, 1 - alpha / 2])
    return float(lo), float(hi)


def load_per_seed(results_dir: Path) -> pd.DataFrame:
    """Flatten the per-seed JSON into a long-form DataFrame."""
    path = results_dir / "per_seed_metrics.json"
    if not path.exists():
        raise FileNotFoundError(f"Missing file: {path}")
    with open(path, "r") as f:
        rows = json.load(f)
    df = pd.json_normalize(rows)
    if "seed" in df.columns:
        df = df.sort_values("seed").reset_index(drop=True)
    return df


def compute_summary(df: pd.DataFrame, metrics: List[str],
                    n_bootstrap: int) -> pd.DataFrame:
    records = []
    for m in metrics:
        if m not in df.columns:
            logger.warning("Metric '%s' not found in per-seed results; skipping", m)
            continue
        values = df[m].dropna().values
        lo, hi = bootstrap_ci(values, n_bootstrap=n_bootstrap)
        records.append({
            "metric": m,
            "n_seeds": int(values.size),
            "mean": float(np.mean(values)),
            "std": float(np.std(values, ddof=1)) if values.size > 1 else 0.0,
            "min": float(np.min(values)),
            "max": float(np.max(values)),
            "ci95_lo": lo,
            "ci95_hi": hi,
        })
    return pd.DataFrame.from_records(records)


def write_latex(summary: pd.DataFrame, out_path: Path, subsample_size: int) -> None:
    """Write a LaTeX tabular block ready to paste into the manuscript."""
    lines = [
        "% Auto-generated by 07_aggregate_multiseed_results.py",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Metric & $N$ seeds & Mean & SD & 95\\% CI & Range \\\\",
        "\\midrule",
    ]
    for _, row in summary.iterrows():
        metric = row["metric"].upper()
        ci = f"[{row['ci95_lo']:.3f}, {row['ci95_hi']:.3f}]"
        rng = f"[{row['min']:.3f}, {row['max']:.3f}]"
        lines.append(
            f"{metric} & {int(row['n_seeds'])} & "
            f"{row['mean']:.3f} & {row['std']:.3f} & {ci} & {rng} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "",
        f"% Subsample size per seed: {subsample_size}",
    ]
    out_path.write_text("\n".join(lines))


def plot_boxplot(df: pd.DataFrame, metrics: List[str], out_path: Path,
                 subsample_size: int) -> None:
    present = [m for m in metrics if m in df.columns]
    if not present:
        logger.warning("No metrics to plot")
        return

    fig, ax = plt.subplots(figsize=(1.4 * len(present) + 1.5, 3.5), dpi=150)
    data = [df[m].dropna().values for m in present]

    bp = ax.boxplot(data, labels=[m.upper() for m in present],
                    widths=0.55, patch_artist=True, showmeans=True)
    for patch in bp["boxes"]:
        patch.set_facecolor("#cfe2f3")
        patch.set_edgecolor("#134f5c")
    for whisker in bp["whiskers"]:
        whisker.set_color("#134f5c")
    for cap in bp["caps"]:
        cap.set_color("#134f5c")
    for median in bp["medians"]:
        median.set_color("#0b5394")
        median.set_linewidth(1.6)

    # Overlay jittered per-seed points
    rng = np.random.default_rng(0)
    for i, values in enumerate(data, start=1):
        x = rng.normal(loc=i, scale=0.04, size=values.size)
        ax.scatter(x, values, s=18, color="#134f5c", alpha=0.75, zorder=3)

    ax.set_ylabel("Score")
    ax.set_title(
        f"MetaGNN robustness across {len(df)} seeds "
        f"($n={subsample_size}$ per subsample)",
        fontsize=10,
    )
    ax.grid(axis="y", linestyle=":", alpha=0.5)
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(
        description="Aggregate multi-seed MetaGNN results."
    )
    parser.add_argument("--results_dir", type=Path, required=True,
                        help="Directory written by 06_multiseed_experiment.py")
    parser.add_argument("--metrics", nargs="+",
                        default=["auroc", "auprc", "f1", "accuracy"],
                        help="Metric keys to aggregate")
    parser.add_argument("--n_bootstrap", type=int, default=10_000,
                        help="Bootstrap resamples for the 95% CI of the mean")
    parser.add_argument("--subsample_size", type=int, default=200,
                        help="Used for figure caption only")
    args = parser.parse_args()

    df = load_per_seed(args.results_dir)
    logger.info("Loaded %d per-seed runs", len(df))

    summary = compute_summary(df, args.metrics, args.n_bootstrap)
    summary_csv = args.results_dir / "summary_stats.csv"
    summary.to_csv(summary_csv, index=False)
    logger.info("Wrote %s", summary_csv)

    summary_tex = args.results_dir / "summary_stats.tex"
    write_latex(summary, summary_tex, args.subsample_size)
    logger.info("Wrote %s", summary_tex)

    boxplot_png = args.results_dir / "multiseed_boxplot.png"
    plot_boxplot(df, args.metrics, boxplot_png, args.subsample_size)
    logger.info("Wrote %s", boxplot_png)

    # Console-friendly summary
    print("\n== Multi-seed summary ==")
    print(summary.to_string(index=False, float_format=lambda v: f"{v:.3f}"))


if __name__ == "__main__":
    main()
